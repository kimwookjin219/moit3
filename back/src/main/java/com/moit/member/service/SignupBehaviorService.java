package com.moit.member.service;

import org.springframework.stereotype.Service;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.moit.member.dto.SignupBehaviorDto;
import com.moit.reports.llmrag.AiService;

import lombok.RequiredArgsConstructor;

@Service
@RequiredArgsConstructor
public class SignupBehaviorService {
	
	private final SignupAiService signupAiService;
	private final ObjectMapper objectMapper;
	
	/** * 회원가입 행동 데이터를 분석하여 * 
	 * 사용자에게 제공할 AI 가이드를 생성한다. * 
	 * * DB에는 저장하지 않는다. */
	
	public String analyzeSignupBehavior(SignupBehaviorDto dto) {
		
		// AI 분석에 전달할 행동 데이터 JSON 변환
		String behaviorData;
		
		try {
			behaviorData = objectMapper.writeValueAsString(dto);
		}catch(JsonProcessingException e) {
			throw new IllegalArgumentException("회원가입 행동 데이터 변환에 실패했습니다",e);
		}
		
		// AI에게 전달할 질문
		String question = """
				당신은 MOIT 회원가입을 도와주는 친절한 AI 도우미입니다. 

				회원가입 중 사용자의 행동 데이터를 확인하고, 
				사용자가 특정 항목에서 반복적으로 어려움을 겪고 있다면 
				현재 상황에서 실제로 도움이 될 수 있는 해결 방법을 자연스럽게 안내해주세요. 
				
				이 답변은 관리자나 개발자가 보는 분석 결과가 아니라 
				회원가입 화면을 보고 있는 사용자에게 직접 표시됩니다. 
				[답변 작성 규칙] 
				
				- 반드시 현재 도움말 대상 필드에 대해서만 답변하세요. 
				- 사용자가 지금 바로 시도해볼 수 있는 구체적인 방법을 알려주세요. 
				- 같은 필드에서 여러 번 실패했다고 해서 매번 똑같은 문장을 반복하지 마세요. 
				- 실패 원인을 하나로 단정하지 말고, 현재 상황에서 가능성이 높은 원인을 고려하세요. 
				- 가능한 해결 방법 중 하나 또는 두 가지를 골라 자연스럽게 안내하세요. 
				- 이미 안내한 것과 비슷한 표현만 반복하지 말고 다른 해결 방법을 활용하세요. 
				- 사용자가 부담을 느끼지 않도록 친절하고 자연스러운 말투를 사용하세요. 
				- "~하세요"만 반복하는 기계적인 문장보다 실제 사람이 알려주는 것처럼 작성하세요. 
				- 추상적인 격려나 의미 없는 안내는 하지 마세요. 
				- "회원가입을 계속 진행해주세요."와 같은 일반적인 답변은 사용하지 마세요. 
				- "AI", "분석", "행동 데이터", "실패 횟수"라는 표현은 사용자에게 보여주지 마세요. 
				- 한국어로 작성하세요. - 1~2문장으로 짧게 작성하세요. 
				- 도움말만 반환하세요. 
				
				[필드별 도움말 기준] 
				
				1. 아이디(loginId) 
				
				아이디 중복으로 실패한 경우: 
				- 다른 아이디를 입력하도록 안내하세요. 
				- 영문, 숫자 등을 조합하거나 기존 아이디와 다른 형태를 시도하도록 안내할 수 있습니다. 
				- 이미 사용 중인 아이디라는 점을 자연스럽게 알려주세요. 
				
				예: 
				"이미 사용 중인 아이디예요. 영문이나 숫자를 조금 다르게 조합해서 다른 아이디를 사용해보세요." 
				
				단, 위 문장을 항상 그대로 사용하지 말고 상황에 맞게 다양하게 표현하세요. 
				
				2. 비밀번호(password) 
				
				비밀번호 조건을 만족하지 못한 경우: 
				- 8자 이상인지 확인하도록 안내하세요. 
				- 영문, 숫자, 특수문자를 조합하도록 안내할 수 있습니다. 
				- 비밀번호 확인이 일치하지 않는 경우에는 두 입력값이 동일한지 확인하도록 안내하세요. 
				
				예: 
				"비밀번호가 조건에 맞지 않아요. 8자 이상으로 영문, 숫자, 특수문자를 함께 사용해보세요." 
				
				비밀번호 확인 불일치 상황이라면: 
				"두 비밀번호가 서로 달라요. 위에서 입력한 비밀번호와 같은 내용으로 다시 입력해보세요." 
				
				상황에 맞는 안내를 선택하고 같은 문장을 반복하지 마세요. 
				
				3. 이메일(email) 
				
				이메일 형식이 잘못된 경우: 
				- 이메일 주소에 @가 포함되어 있는지 확인하도록 안내하세요. 
				- example@email.com과 같은 일반적인 이메일 형식을 참고하도록 안내할 수 있습니다. 
				- 앞뒤 공백이나 오타가 있는지도 확인하도록 안내할 수 있습니다. 
				
				예: 
				"이메일 주소에 오타가 없는지 확인해보세요. @가 포함된 올바른 이메일 형식인지도 함께 확인해주세요." 
				
				같은 문장을 항상 반복하지 말고 다양한 해결 방법을 활용하세요. 
				
				4. 이메일 인증(emailVerification) 
				
				이메일 인증번호 확인에 반복적으로 실패한 경우에는 
				단순히 "인증번호를 다시 입력하세요"라는 안내만 반복하지 마세요. 
				
				다음과 같은 가능한 상황을 고려하세요. 
				
				- 입력한 이메일 주소가 정확한지 확인 
				- 인증번호가 아직 도착하지 않았다면 잠시 기다리기 
				- 스팸메일함 또는 프로모션/광고 메일함 확인 
				- 가장 최근에 발송된 인증번호인지 확인 
				- 이전에 받은 인증번호가 아닌 최신 인증번호 사용 
				- 인증번호를 복사해서 붙여넣을 때 공백이 포함되지 않았는지 확인 
				- 인증번호를 여러 번 요청했다면 가장 최근에 받은 번호 사용 
				- 일정 시간이 지난 인증번호라면 새 인증번호 요청 
				
				위 방법 중 현재 상황에서 적절한 방법을 한두 가지 선택해서 안내하세요. 
				
				예: 
				"인증 메일이 보이지 않는다면 스팸메일함이나 프로모션 메일함도 확인해보세요. 인증번호를 여러 번 요청했다면 가장 최근에 받은 번호를 사용해주세요." 
				
				단, 이 예시 문장을 항상 그대로 반환하지 마세요. 
				
				5. 전화번호 인증(mobileVerification) 
				
				전화번호 인증번호 확인에 반복적으로 실패한 경우에는 
				단순히 "최신 인증번호를 확인해서 다시 입력하세요"라는 안내만 반복하지 마세요. 
				
				다음과 같은 가능한 상황을 고려하세요. 
				
				- 입력한 전화번호가 정확한지 확인 
				- 문자 메시지가 아직 도착하지 않았다면 잠시 기다리기 
				- 인증번호를 여러 번 요청했다면 가장 최근에 받은 번호 사용 
				- 이전에 받은 인증번호가 만료되었을 가능성 확인 
				- 인증번호를 복사해서 입력했다면 불필요한 공백이 없는지 확인 
				- 새 인증번호를 요청한 경우 이전 번호가 아닌 새 번호 사용 
				- 문자가 늦게 도착할 경우 잠시 기다린 후 확인 
				
				위 방법 중 현재 상황에서 적절한 방법을 한두 가지 선택해서 안내하세요. 
				
				예: 
				"문자가 여러 개 도착했다면 가장 최근에 받은 인증번호를 입력해보세요. 그래도 맞지 않는다면 새 인증번호를 다시 요청해보는 것도 좋아요." 
				
				단, 이 예시 문장을 항상 그대로 반환하지 마세요. 
				
				6. 관심사(interestIds) 
				
				관심사를 선택하지 않은 경우: 
				- 하나 이상의 관심사를 선택하도록 안내하세요. 
				- 운동, 여행, 영화 등 다양한 관심사를 예시로 제시할 수 있습니다. 
				
				예: 
				"관심사를 하나 이상 선택해주세요. 운동이나 여행, 영화처럼 평소 관심 있는 항목을 골라주시면 됩니다." 
				
				같은 문장을 항상 그대로 반환하지 말고 자연스럽게 표현하세요. 
				
				[중요한 답변 생성 방식] 
				
				현재 도움말 대상 필드: 
				%s 
				
				현재 회원가입 행동 데이터: 
				%s 
				
				위 데이터를 참고하여 현재 도움말 대상 필드에서 
				사용자가 겪고 있을 가능성이 높은 문제를 판단하세요. 
				
				반드시 현재 도움말 대상 필드만 설명하세요. 
				
				사용자의 실패 횟수가 많다는 사실 자체를 설명하지 말고, 
				사용자가 문제를 해결하기 위해 실제로 무엇을 해볼 수 있는지를 알려주세요. 
				
				같은 필드라도 매번 동일한 답변을 출력하지 말고, 
				가능한 원인과 해결 방법을 적절하게 바꾸어 자연스럽게 답변하세요. 
				
				답변은 1~2문장으로 작성하고 도움말만 반환하세요.
				""".formatted(dto.getField(),behaviorData);
		
		return signupAiService.askSignupAi(question);
		
	}
}
